# 4. 安全中间件（AgentMiddleware 模式）
# ============================================================
class SafetyMiddleware:
    """安全中间件：在模型输出后检测危险工具调用并记录日志。"""
    name = "safety_checker"
    dangerous_keywords = ["delete", "destroy", "drop", "wipe"]

    def after_model(self, state: dict[str, Any], runtime=None) -> dict[str, Any] | None:
        messages = state.get("messages", [])
        if not messages:
            return None
        last_message = messages[-1]
        tool_calls = getattr(last_message, "tool_calls", None) or []
        for tc in tool_calls:
            tool_name = tc.get("name", "").lower()
            for kw in self.dangerous_keywords:
                if kw in tool_name:
                    print(f"   [SAFETY] Dangerous operation detected!")
                    print(f"   Tool: {tc.get('name')}")
                    print(f"   Args: {tc.get('args')}")
        return None


class RequestLoggerMiddleware:
    """请求日志中间件：在模型调用前后打印调试信息。"""
    name = "request_logger"

    def before_model(self, state: dict[str, Any], runtime=None) -> dict[str, Any] | None:
        message_count = len(state.get("messages", []))
        print(f"[BEFORE MODEL] Processing {message_count} messages")
        return None

    def after_model(self, state: dict[str, Any], runtime=None) -> dict[str, Any] | None:
        messages = state.get("messages", [])
        if messages:
            last = messages[-1]
            tool_calls = getattr(last, "tool_calls", None) or []
            if tool_calls:
                print(f"[AFTER MODEL] Model requested {len(tool_calls)} tool call(s)")
            else:
                print(f"[AFTER MODEL] Model provided final response")
        return None
