# 2. HITL 工具：带人工审批中断
# ============================================================
@tool
def send_email_hitl(to_address: str, subject: str, body: str) -> str:
    """给指定的电子邮箱发送邮件——此操作需要人工审批。"""
    response = interrupt({
        "type": "tool_approval",
        "tool_name": "send_email",
        "args": {
            "to_address": to_address,
            "subject": subject,
            "body": body,
        },
        "message": "请审核此邮件。您可以选择批准、拒绝或进行编辑。",
        "severity": "medium",
    })

    if response.get("action") == "approve":
        return f"【工具返回】已成功向 <{to_address}> 发送主题为《{subject}》的邮件，内容大小：{len(body)} 字节。"
    elif response.get("action") == "reject":
        return "【工具返回】邮件发送已被用户取消。"
    elif response.get("action") == "edit":
        to_address = response.get("to_address", to_address)
        subject = response.get("subject", subject)
        body = response.get("body", body)
        return (
            f"【工具返回】已使用编辑后的内容发送邮件：\n"
            f"收件人: {to_address}\n"
            f"主题: {subject}\n"
            f"正文: {body}"
        )
    return "【工具返回】未知的响应类型，操作已取消。"


@tool
def delete_database(database_name: str) -> str:
    """删除数据库。此操作极其危险！"""
    response = interrupt({
        "type": "tool_approval",
        "tool_name": "delete_database",
        "args": {"database_name": database_name},
        "message": "你绝对确定要删除这个数据库吗？此操作不可撤销！",
        "severity": "high",
    })
    if response.get("action") == "approve":
        return f"【工具返回】数据库 '{database_name}' 已被删除（模拟操作）。"
    else:
        return "【工具返回】数据库删除操作已被取消。"


@tool
def make_purchase(item_name: str, amount: float) -> str:
    """进行采购。超过 $1000 的采购需要人工审批。"""
    if amount > 1000:
        response = interrupt({
            "type": "tool_approval",
            "tool_name": "make_purchase",
            "args": {"item_name": item_name, "amount": amount},
            "message": f"采购金额 ${amount:.2f} 超过 $1000 阈值，需要人工审批。",
            "severity": "high",
            "reason": "amount_exceeds_threshold",
        })
        if response.get("action") == "approve":
            return f"【工具返回】已批准采购 {item_name}，金额 ${amount:.2f}。"
        elif response.get("action") == "reject":
            return f"【工具返回】采购 {item_name}（${amount:.2f}）已被拒绝。"
        else:
            return "【工具返回】采购操作已取消。"
    else:
        return f"【工具返回】已自动完成采购 {item_name}，金额 ${amount:.2f}。"


