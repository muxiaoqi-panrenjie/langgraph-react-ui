@tool
def write_code(language: str, requirement: str) -> str:
    """根据需求编写指定编程语言的代码。"""
    lang = language.lower().strip()
    if "python" in lang or "py" in lang:
        code = (
            "```python\n"
            "def binary_search(arr, target):\n"
            "    # Requirement: " + requirement + "\n"
            "    low, high = 0, len(arr) - 1\n"
            "    while low <= high:\n"
            "        mid = (low + high) // 2\n"
            "        if arr[mid] == target:\n"
            "            return mid\n"
            "        elif arr[mid] < target:\n"
            "            low = mid + 1\n"
            "        else:\n"
            "            high = mid - 1\n"
            "    return -1\n"
            "```"
        )
    elif "java" in lang or "jvm" in lang:
        code = (
            "```java\n"
            "public class Solution {\n"
            "    // Requirement: " + requirement + "\n"
            "    public static void main(String[] args) {\n"
            "        System.out.println(\"Hello Code Agent!\");\n"
            "    }\n"
            "}\n"
            "```"
        )
    else:
        code = (
            "```javascript\n"
            "// Requirement: " + requirement + "\n"
            "function solve() {\n"
            "    console.log('Code generated by Code Agent');\n"
            "}\n"
            "```"
        )
    return f"【工具返回】已为您生成相关的 {language} 代码：\n\n{code}"


